//! Web 出口帧契约的 TypeScript 导出程序 — 由定义帧的出口自己拥有。
//!
//! 与 `rpc-api/examples/export_contracts.rs` 分工: 那个程序导出 RPC/领域
//! 合同, 这里导出 [`backend_server::frames`] 的 WebSocket/HTTP 帧与协议常量。
//! 两个程序都写进同一个 `TS_RS_EXPORT_DIR` — 契约目录是前端的一份投影,
//! 而不是某个 crate 的私有产物; 这样也避免让 `rpc-api` (L4) 反向 dev-depend
//! `backend-server` (L5)。
//!
//! 每个导出的类型都会打印一行机读清单, 供 `scripts/check-contracts.mjs`:
//! - 检测两个不同的 Rust 类型写同一个 `<TypeName>.ts` (M10 的静默覆盖);
//! - 检测前端重新声明 `wire` 角色的帧类型 (M3 的回归)。
//!
//! 清单格式: `ts-rs-export\t<Rust 类型路径>\t<相对输出文件>\t<角色>`。
//!
//! 另外把协议常量 (帧头 / 版本 / 子协议 / 令牌前缀) 生成为 `WebProtocol.ts`,
//! 使这些字面量在前端只有一处定义; ts-rs 只能导出类型, 常量由本程序写入。
//!
//! 运行: `pnpm generate:contracts` / `pnpm check:contracts` (两者都会设置
//! `TS_RS_EXPORT_DIR` 与 `TS_RS_LARGE_INT=number`)。输出必须确定性,
//! `check:contracts` 会逐字节比对。

use std::path::Path;

use backend_server::frames;
use backend_server::http;
use ts_rs::{Config, TS};

/// 导出一个类型并打印机读清单行; 角色的 `wire` 表示这是出口自己的帧契约。
///
/// `output_path` 为 `None` 说明类型不可导出 (例如内联的泛型实例), 记为失败
/// 而不是让它悄悄消失。
macro_rules! export {
    ($cfg:expr, $role:literal, $($t:ty),+ $(,)?) => {{
        let mut failures: Vec<String> = Vec::new();
        $(
            match <$t as TS>::output_path() {
                Some(path) => println!(
                    "ts-rs-export\t{}\t{}\t{}",
                    std::any::type_name::<$t>(),
                    path.display(),
                    $role
                ),
                None => failures.push(format!("{}: not exportable", stringify!($t))),
            }
            if let Err(err) = <$t as TS>::export($cfg) {
                failures.push(format!("{}: {err}", stringify!($t)));
            }
        )+
        failures
    }};
}

/// 协议常量模块 — 前端唯一字面量来源。
fn write_protocol_module(out_dir: &str) -> std::io::Result<()> {
    let source = format!(
        "// This file was generated by \
         src-tauri/crates/desktop/backend-server/examples/export_frames.rs.\n\
         // Do not edit this file manually.\n\
         \n\
         /** Binary stream frame version — a client rejects a header it does not know. */\n\
         export const BINARY_FRAME_VERSION = {};\n\
         /** Binary stream frame header length (version + format + subscription id + payload len). */\n\
         export const BINARY_FRAME_HEADER = {};\n\
         \n\
         /** Web exit protocol version reported by `/api/v1/handshake`. */\n\
         export const PROTOCOL_VERSION = {:?};\n\
         \n\
         /** WebSocket subprotocol, and the prefix that carries the bearer token with it. */\n\
         export const WS_SUBPROTOCOL = {:?};\n\
         export const WS_TOKEN_PREFIX = {:?};\n",
        frames::BINARY_FRAME_VERSION,
        frames::BINARY_FRAME_HEADER,
        frames::PROTOCOL_VERSION,
        http::WS_SUBPROTOCOL,
        http::WS_TOKEN_PREFIX,
    );
    std::fs::write(Path::new(out_dir).join("WebProtocol.ts"), source)
}

fn main() {
    let cfg = Config::from_env();
    let out_dir = std::env::var("TS_RS_EXPORT_DIR").unwrap_or_else(|_| "./bindings".into());
    println!("exporting Web exit contracts to {out_dir}");

    let mut failures = export! { &cfg, "wire",
        frames::ServerMessage,
        frames::ClientMessage,
        frames::RpcRequest,
        frames::RpcResponse,
        frames::Capabilities,
    };
    // `serde_json::Value` 是所有 `Value` 字段的引用依赖: 导出清单必须是
    // 依赖的闭包, 否则前端的 `JsonValue` 导入悬空 (与 export_contracts.rs 同理)。
    failures.extend(export! { &cfg, "dep",
        serde_json::Value,
    });

    if let Err(err) = write_protocol_module(&out_dir) {
        failures.push(format!("WebProtocol.ts: {err}"));
    }

    if failures.is_empty() {
        println!("web exit contract export finished");
    } else {
        for failure in &failures {
            eprintln!("export failed: {failure}");
        }
        std::process::exit(1);
    }
}
