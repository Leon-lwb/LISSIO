//! Regenerates docs/architecture/motion-tokens.md from the live spring solver.
//!
//! Run via `pnpm docs:motion`. The table is derived from the same functions the
//! app calls at runtime, so it cannot drift from the code the way a hand-written
//! table does.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { createServer } from 'vite';

// Load the solver through the project's own bundler rather than plain Node: the
// motion modules use extensionless relative imports (the TS/Vite convention), so
// resolving them here with the same rules the app uses is what keeps the generated
// table honest. `vite-node` would do the same job but is not a dependency.
const vite = await createServer({
  configFile: false,
  appType: 'custom',
  logLevel: 'error',
  server: { middlewareMode: true },
});
const spring = await vite.ssrLoadModule('/src/lib/motion/spring.ts');
const { allMotionTokens, timingAt, REFLOW_TIMING, SPEED_SCALE } =
  await vite.ssrLoadModule('/src/lib/motion/motionConfig.ts');
const { springAt, springFromTiming, springSettleTime, spatialTiming } = spring;

function peak(spring, settle) {
  let max = 0;
  for (let i = 0; i <= 600; i += 1) max = Math.max(max, springAt(spring, (i / 600) * settle));
  return max;
}

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, '../docs/architecture/motion-tokens.md');

const rows = allMotionTokens().map(({ family, phase, speed }) => {
  const timing = timingAt(family, phase, speed);
  const spring = springFromTiming(timing);
  const settle = springSettleTime(spring);
  return {
    speed,
    family,
    phase,
    duration: Math.round(timing.duration * 1000),
    bounce: timing.bounce.toFixed(2),
    stiffness: spring.stiffness.toFixed(1),
    damping: spring.damping.toFixed(2),
    overshoot: `${((peak(spring, settle) - 1) * 100).toFixed(1)}%`,
  };
});

const table = (speed) =>
  [
    '| Family | Phase | Duration | Bounce | Stiffness k | Damping c | Peak overshoot |',
    '| --- | --- | ---: | ---: | ---: | ---: | ---: |',
    ...rows
      .filter((r) => r.speed === speed)
      .map(
        (r) =>
          `| \`${r.family}\` | ${r.phase} | ${r.duration}ms | ${r.bounce} | ${r.stiffness} | ${r.damping} | ${r.overshoot} |`
      ),
  ].join('\n');

const REFLOW_SPEEDS = ['fast', 'standard', 'relaxed'];

const reflowRows = REFLOW_SPEEDS.map((speed) => {
  const scale = SPEED_SCALE[speed];
  const timing = {
    duration: REFLOW_TIMING.duration * scale.duration,
    bounce: REFLOW_TIMING.bounce * scale.bounce,
  };
  const spring = springFromTiming(timing);
  const settle = springSettleTime(spring);
  // Reflow is stretched by measured distance. Pass speed explicitly because
  // `reflowSpring()` reads speed from the DOM and would resolve to standard here.
  const yieldAt = (distancePx) =>
    Math.round(springSettleTime(springFromTiming(spatialTiming(timing, distancePx))) * 1000);
  return {
    speed,
    duration: Math.round(timing.duration * 1000),
    stiffness: spring.stiffness.toFixed(1),
    damping: spring.damping.toFixed(2),
    yield20: yieldAt(20),
    yield400: yieldAt(400),
    overshoot: `${((peak(spring, settle) - 1) * 100).toFixed(1)}%`,
  };
});

const reflowTable = [
  '| Speed | Base duration | Stiffness k | Damping c | One row (20 px) | Large yield (400 px) | Peak overshoot |',
  '| --- | ---: | ---: | ---: | ---: | ---: | ---: |',
  ...reflowRows.map(
    (r) =>
      `| ${r.speed} | ${r.duration}ms | ${r.stiffness} | ${r.damping} | ${r.yield20}ms | ${r.yield400}ms | ${r.overshoot} |`
  ),
].join('\n');

const doc = `# Motion Tokens and Tuning Tables

<!-- lissio-doc
status: maintained
owner: Lissio maintainers
last-reviewed: 2026-10-07
applies-to: Spring timing tokens derived from src/lib/motion
-->

This file is generated by \`pnpm docs:motion\` directly from the solver in
\`src/lib/motion/spring.ts\`. Do not edit it by hand; generated values must not
drift from runtime code.

## Physical model

Each token is a damped harmonic oscillator: unit mass attached to a spring and
released from rest toward a target.

    ẍ = (−k·x − c·ẋ) / m,  m = 1

- \`k\` is stiffness; larger values converge faster.
- \`c\` is damping; larger values are more stable and smaller values oscillate.
- Damping ratio ζ = c / (2√k). ζ < 1 overshoots; ζ = 1 is critically damped.

Unlike cubic Bézier interpolation, this is an integrated physical system:

1. **Overshoot is solved, not drawn.** Peak overshoot is determined by ζ.
2. **Duration is solved, not merely declared.** \`springFromTiming()\` solves for
   stiffness that enters the target settling band at the requested duration.

## Entry and exit behavior

Entry is an arrival. A small overshoot reads as elasticity after the object
reaches its destination. Exit is a departure. An exiting panel that continues
oscillating reads as a rendering fault. Therefore every \`out\` token has zero
bounce. \`motionConfig.ts\` owns this in \`BASE_TIMING\`, and tests lock it.

## Five families

Families are ordered by how much screen distance changes, not by component type.

| Family | Purpose | Typical users |
| --- | --- | --- |
| \`control\` | Hover, press, focus | Buttons, inputs, icons |
| \`toggle\` | Binary or continuous control changes | Switches, sliders, knobs |
| \`content\` | Content-level appearance and removal | Rows, messages, toasts, banners |
| \`surface\` | Anchored floating surfaces | Dialogs, menus, tooltips |
| \`spatial\` | Large spatial movement | Docked panels, floating windows, docks |

## Tuning tables

### standard

${table('standard')}

### fast

${table('fast')}

### relaxed

${table('relaxed')}

## Reflow and yielding

Reflow is a local list displacement: one row disappears or changes order and
neighbors move by a slot. It is intentionally faster than any family because
the event is smaller than a whole surface arriving or leaving.

This is not a sixth family. It is the named \`REFLOW_TIMING\` plus
\`reflowSpring()\`. The motion is stretched by measured distance through
\`spatialTiming()\`, so removing an expanded block can take longer than moving a
single row.

${reflowTable}

Zero bounce is intentional: yielding has no source object or momentum.

## Tuning

Change feel through \`BASE_TIMING\` in
\`src/lib/motion/motionConfig.ts\`. Do not add call-site timing constants.

| Desired effect | Change |
| --- | --- |
| Faster or slower overall | Use the in-app motion speed setting |
| Crisper family | Reduce \`BASE_TIMING[family].in.duration\` |
| More visible elasticity | Increase \`BASE_TIMING[family].in.bounce\` |
| More deliberate long travel | Already handled by \`spatialTiming()\` |
| Faster list yielding | Change \`REFLOW_TIMING.duration\` |
| Different floating origin | Pass \`MotionPresence\` \`origin\` / \`travel\` |

Useful bounce is approximately 0 to 0.45. Higher values flash rather than read
as elasticity. Bounce and stiffness are not monotonically related; tune by the
reported peak overshoot.

## One token, three projections

    motionConfig.ts -> easingTokens.ts -> CSS --ease-<family>-<phase>
                    -> gsapSpring.ts -> GSAP tweens

CSS samples the spring into a \`linear()\` easing. CSS transitions and GSAP
tweens use the same solver and therefore match for the same token.

## Distance awareness

\`springFromTiming()\` answers how long an animation takes. \`spatialTiming()\`
also scales duration and bounce by measured distance, capped at 1.35×, because
long travel exposes more of the settling phase. Fixed entry offsets use nominal
distance; FLIP and dock reorder use actual pixel distance.
`;
writeFileSync(out, doc);
await vite.close();
console.log(`wrote ${out}`);
